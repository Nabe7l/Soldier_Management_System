-- Query 1: Display all soldiers
SELECT * FROM soldiers;

-- Query 2: Display active soldiers
SELECT *
FROM soldiers
WHERE status = 'Active';

-- Query 3: Display soldiers with rank names
SELECT s.soldier_id, s.first_name, s.last_name, r.rank_name
FROM soldiers s
JOIN ranks r ON s.rank_id = r.rank_id;

-- Query 4: Display soldiers with unit names
SELECT s.soldier_id, s.first_name, s.last_name, u.unit_name
FROM soldiers s
JOIN units u ON s.unit_id = u.unit_id;

-- Query 5: Count soldiers in each unit
SELECT u.unit_name, COUNT(s.soldier_id) AS total_soldiers
FROM units u
LEFT JOIN soldiers s ON u.unit_id = s.unit_id
GROUP BY u.unit_id, u.unit_name
ORDER BY u.unit_id;

-- Query 6: Display retired soldiers
SELECT soldier_id, first_name, last_name, status
FROM soldiers
WHERE status = 'Retired';

-- Query 7: Count soldiers in each rank
SELECT r.rank_name, COUNT(s.soldier_id) AS total_soldiers
FROM ranks r
LEFT JOIN soldiers s ON r.rank_id = s.rank_id
GROUP BY r.rank_id, r.rank_name
ORDER BY r.rank_id;

-- Query 8: Display soldiers enlisted after 2020
SELECT soldier_id, first_name, last_name, enlistment_date
FROM soldiers
WHERE enlistment_date >= '2021-01-01'
ORDER BY enlistment_date;

-- Query 9: Display soldiers with rank and unit
SELECT s.soldier_id, s.first_name, s.last_name,
       r.rank_name, u.unit_name
FROM soldiers s
JOIN ranks r ON s.rank_id = r.rank_id
JOIN units u ON s.unit_id = u.unit_id;

-- Query 10: Display soldiers ordered by date of birth
SELECT soldier_id, first_name, last_name, date_of_birth
FROM soldiers
ORDER BY date_of_birth ASC;


