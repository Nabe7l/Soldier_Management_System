-- Create a view for soldier details
CREATE VIEW soldier_details AS
SELECT
    s.soldier_id,
    s.service_number,
    s.first_name,
    s.last_name,
    r.rank_name,
    u.unit_name,
    s.status
FROM soldiers s
JOIN ranks r ON s.rank_id = r.rank_id
JOIN units u ON s.unit_id = u.unit_id;

-- Display the view
